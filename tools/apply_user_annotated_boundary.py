def main():
    # Remove consecutive duplicate coordinates
    dedup_coords = []
    for pt in USER_BOUNDARY_COORDS:
        if not dedup_coords or dedup_coords[-1] != pt:
            dedup_coords.append(pt)
    if dedup_coords[0] != dedup_coords[-1]:
        dedup_coords.append(dedup_coords[0])

    outer_geom = make_valid(Polygon(dedup_coords))

    # Base partitioning geometries (covering the full bounding space)
    raw_areas = [
        (
            "Area 1", "A1",
            Polygon([(121.100, 14.734), (121.136, 14.734), (121.136, 14.736), (121.100, 14.736), (121.100, 14.734)])
        ),
        (
            "Area 2", "A2",
            Polygon([(121.100, 14.736), (121.134, 14.736), (121.134, 14.770), (121.100, 14.770), (121.100, 14.736)])
        ),
        (
            "Area 3", "A3",
            MultiPolygon([
                Polygon([(121.100, 14.700), (121.133, 14.700), (121.133, 14.734), (121.100, 14.734), (121.100, 14.700)]),
                Polygon([(121.134, 14.736), (121.160, 14.736), (121.160, 14.770), (121.134, 14.770), (121.134, 14.736)])
            ])
        ),
        (
            "Area 4", "A4",
            Polygon([(121.133, 14.730), (121.140, 14.730), (121.140, 14.734), (121.133, 14.734), (121.133, 14.730)])
        ),
        (
            "Area 5", "A5",
            MultiPolygon([
                Polygon([(121.136, 14.734), (121.160, 14.734), (121.160, 14.736), (121.136, 14.736), (121.136, 14.734)]),
                Polygon([(121.140, 14.730), (121.160, 14.730), (121.160, 14.734), (121.140, 14.734), (121.140, 14.730)])
            ])
        ),
        (
            "Area 6", "A6",
            Polygon([(121.133, 14.700), (121.160, 14.700), (121.160, 14.730), (121.133, 14.730), (121.133, 14.700)])
        ),
    ]

    features = []
    for name, code, geom in raw_areas:
        clipped = geom.intersection(outer_geom)
        if isinstance(clipped, Polygon):
            clipped = MultiPolygon([clipped])
        
        geom_dict = mapping(clipped)
        features.append({
            "type": "Feature",
            "properties": {
                "name": name,
                "code": code,
                "boundary_source": "approximate"
            },
            "geometry": geom_dict
        })

    fc = {
        "type": "FeatureCollection",
        "name": "san_jose_areas_approx",
        "crs": { "type": "name", "properties": { "name": "urn:ogc:def:crs:OGC:1.3:CRS84" } },
        "features": features
    }

    geojson_path = "dataset/derived/san_jose_areas_approx.geojson"
    with open(geojson_path, "w") as f:
        json.dump(fc, f, indent=2)
    print(f"Successfully generated {geojson_path} from user boundary coordinates!")

if __name__ == "__main__":
    main()
